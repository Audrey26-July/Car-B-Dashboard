def heading_numbering(doc):
    """Link Heading 1-3 to a real multilevel decimal list so numbers are automatic."""
    numbering = doc.part.numbering_part.element
    h1 = doc.styles["Heading 1"].style_id
    h2 = doc.styles["Heading 2"].style_id
    h3 = doc.styles["Heading 3"].style_id
    lvl_texts = ["{a}", "{a}.{b}", "{a}.{b}.{c}"] + ["{a}.{b}.{c}.{d}"] * 6
    lvl_styles = [h1, h2, h3] + [None] * 6
    levels = []
    for ilvl, (text, style_id) in enumerate(zip(lvl_texts, lvl_styles)):
        pstyle = '<w:pStyle w:val="%s"/>' % style_id if style_id else ""
        literal = text.format(a="%1", b="%2", c="%3", d="%4")
        levels.append(
            '<w:lvl w:ilvl="{i}"><w:start w:val="1"/><w:numFmt w:val="decimal"/>'
            "{pstyle}<w:suff w:val=\"space\"/>"
            '<w:lvlText w:val="{txt}"/><w:lvlJc w:val="left"/>'
            '<w:pPr><w:ind w:left="0" w:hanging="0"/></w:pPr>'
            '<w:rPr><w:rFonts w:ascii="Calibri" w:hAnsi="Calibri"'
            ' w:eastAsia="Microsoft YaHei" w:cs="Calibri"/></w:rPr></w:lvl>'.format(
                i=ilvl, pstyle=pstyle, txt=literal
            )
        )
    abstract = parse_xml(
        '<w:abstractNum {ns} w:abstractNumId="{aid}">'
        '<w:multiLevelType w:val="multilevel"/>{levels}</w:abstractNum>'.format(
            ns=nsdecls("w"), aid=NUM_ID, levels="".join(levels)
        )
    )
    first_num = numbering.find(qn("w:num"))
    if first_num is not None:
        first_num.addprevious(abstract)
    else:
        numbering.append(abstract)
    numbering.append(
        parse_xml(
            '<w:num {ns} w:numId="{nid}"><w:abstractNumId w:val="{aid}"/></w:num>'.format(
                ns=nsdecls("w"), nid=NUM_ID, aid=NUM_ID
            )
        )
    )


def unnumber(paragraph):
    """Turn off list numbering for a single paragraph (used by the appendix heading)."""
    pPr = paragraph._p.get_or_add_pPr()
    numPr = OxmlElement("w:numPr")
    numPr.append(OxmlElement("w:ilvl"))
    numPr.find(qn("w:ilvl")).set(qn("w:val"), "0")
    numId = OxmlElement("w:numId")
    numId.set(qn("w:val"), "0")
    numPr.append(numId)
    insert_ordered(pPr, numPr, PPR_ORDER)


def add_toc(doc, levels="1-3"):
    p = doc.add_paragraph()
    fmt_run(p.add_run(""), size=11)
    run = p.add_run()
    begin = OxmlElement("w:fldChar")
    begin.set(qn("w:fldCharType"), "begin")
    instr = OxmlElement("w:instrText")
    instr.set(qn("xml:space"), "preserve")
    instr.text = ' TOC \\o "%s" \\h \\z \\u ' % levels
    separate = OxmlElement("w:fldChar")
    separate.set(qn("w:fldCharType"), "separate")
    placeholder = OxmlElement("w:t")
    placeholder.text = "目录将在文档打开时自动生成（如未显示，请按 Ctrl+A 后按 F9 更新域）"
    end = OxmlElement("w:fldChar")
    end.set(qn("w:fldCharType"), "end")
    run._r.append(begin)
    run._r.append(instr)
    run._r.append(separate)
    run._r.append(placeholder)
    run._r.append(end)
    fmt_run(run, size=10, color="6B7280")
    return p


def enable_update_fields(doc):
    settings = doc.settings.element
    for tag in ("w:updateFields",):
        for old in settings.findall(qn(tag)):
            settings.remove(old)
    el = OxmlElement("w:updateFields")
    el.set(qn("w:val"), "true")
    settings.append(el)


